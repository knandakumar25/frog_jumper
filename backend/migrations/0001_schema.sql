-- Accounts schema, matching what Django's accounts migrations 0001-0007 created.
--
-- On the existing database (made by Django) every block below is skipped, because each table
-- already exists; nothing there is altered or re-indexed. On a fresh database the same tables,
-- columns, unique keys and checks are created, so the Express API works the same on both.
--
-- Differences from Django on a FRESH database only:
-- * Column defaults are set (Django supplied defaults in Python, not in the table). The API
--   always writes every column, so this only helps manual inserts.
-- * Foreign keys carry ON DELETE actions that match the old models (Django emulated them in
--   Python): sessions and 2FA codes are deleted with their user; a pending registration keeps
--   its row when its browser session goes.
-- Django's own tables (django_*, auth_*, accounts_user_groups, accounts_user_user_permissions)
-- are not created; the API never used them.

DO $$
BEGIN
  IF to_regclass('public.accounts_user') IS NULL THEN
    CREATE TABLE accounts_user (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      password varchar(128) NOT NULL,
      last_login timestamptz,
      is_superuser boolean NOT NULL DEFAULT false,
      username varchar(150) NOT NULL UNIQUE,
      first_name varchar(150) NOT NULL DEFAULT '',
      last_name varchar(150) NOT NULL DEFAULT '',
      is_staff boolean NOT NULL DEFAULT false,
      is_active boolean NOT NULL DEFAULT true,
      date_joined timestamptz NOT NULL DEFAULT now(),
      email varchar(254) NOT NULL UNIQUE,
      profile_picture text NOT NULL DEFAULT '',
      is_2fa_enabled boolean NOT NULL DEFAULT false,
      country varchar(100),
      phone_number varchar(20),
      clerk_user_id varchar(64) UNIQUE,
      date_of_birth date
    );
  END IF;

  IF to_regclass('public.accounts_browsersession') IS NULL THEN
    CREATE TABLE accounts_browsersession (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      session_id uuid NOT NULL UNIQUE,
      created_at timestamptz NOT NULL DEFAULT now(),
      is_authorized boolean NOT NULL DEFAULT false,
      user_id bigint REFERENCES accounts_user (id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
      secret_hash varchar(64) NOT NULL DEFAULT '',
      expires_at timestamptz,
      consumed_at timestamptz,
      cancelled_at timestamptz,
      intent varchar(8) NOT NULL DEFAULT 'login',
      locale varchar(32) NOT NULL DEFAULT 'en-US'
    );
    CREATE INDEX accounts_browsersession_user_id_idx ON accounts_browsersession (user_id);
  END IF;

  IF to_regclass('public.accounts_pendingregistration') IS NULL THEN
    CREATE TABLE accounts_pendingregistration (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      clerk_user_id varchar(64) NOT NULL UNIQUE,
      email varchar(254) NOT NULL,
      token_hash varchar(64) NOT NULL UNIQUE,
      first_name varchar(150) NOT NULL DEFAULT '',
      last_name varchar(150) NOT NULL DEFAULT '',
      clerk_username varchar(150) NOT NULL DEFAULT '',
      request_ip inet,
      sent_count integer NOT NULL DEFAULT 0 CHECK (sent_count >= 0),
      created_at timestamptz NOT NULL DEFAULT now(),
      last_sent_at timestamptz NOT NULL,
      expires_at timestamptz NOT NULL,
      completed_at timestamptz,
      browser_session_id bigint REFERENCES accounts_browsersession (id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED
    );
    CREATE INDEX accounts_pendingregistration_browser_session_id_idx
      ON accounts_pendingregistration (browser_session_id);
  END IF;

  IF to_regclass('public.accounts_twofactorcode') IS NULL THEN
    CREATE TABLE accounts_twofactorcode (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      code varchar(6) NOT NULL,
      created_at timestamptz NOT NULL DEFAULT now(),
      is_verified boolean NOT NULL DEFAULT false,
      purpose varchar(20) NOT NULL,
      session_id uuid,
      user_id bigint NOT NULL REFERENCES accounts_user (id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED
    );
    CREATE INDEX accounts_twofactorcode_user_id_idx ON accounts_twofactorcode (user_id);
  END IF;
END
$$;
