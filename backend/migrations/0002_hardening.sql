-- Security fixes approved by the owner on 2026-11-15 (applies to old and new databases alike).
--
-- 1. 2FA codes count wrong guesses. After five, the code is dead even if the sixth guess is
--    right, so a 6-digit code can no longer be brute-forced inside its 10 minutes.
ALTER TABLE accounts_twofactorcode ADD COLUMN IF NOT EXISTS attempts integer NOT NULL DEFAULT 0;

-- 2. Refresh tokens are single use. Each issued refresh token's id (`jti`) is recorded here;
--    redeeming one sets `used_at`, and a second redemption of the same token is refused. Django's
--    rotation issued new tokens but never revoked the old ones.
CREATE TABLE IF NOT EXISTS accounts_refreshtoken (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  jti uuid NOT NULL UNIQUE,
  user_id bigint NOT NULL REFERENCES accounts_user (id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL,
  used_at timestamptz
);
CREATE INDEX IF NOT EXISTS accounts_refreshtoken_user_id_idx ON accounts_refreshtoken (user_id);
CREATE INDEX IF NOT EXISTS accounts_refreshtoken_expires_at_idx ON accounts_refreshtoken (expires_at);
