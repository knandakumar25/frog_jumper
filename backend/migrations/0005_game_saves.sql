-- Game saves belong to accounts (owner decision, 2026-11-18).
--
-- Until now the game opened PostgreSQL itself and wrote global, unowned rows (`game_sessions`,
-- `game_state`). Saves now go through the API (src/routes/game.js) and every row belongs to one
-- account. The game still calculates rewards and world state; the server stores them with
-- all-or-nothing commits, retry-safe receipts and a per-slot revision for conflict detection.
--
-- The owner chose to discard the old saves, so the old tables are dropped (a backup was taken
-- with tools/db/backup.ps1 on 2026-11-18 before this ran).

DROP TABLE IF EXISTS game_state;
DROP TABLE IF EXISTS game_sessions;

-- One campaign save slot.
CREATE TABLE IF NOT EXISTS game_slot (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES accounts_user (id) ON DELETE CASCADE,
  character text NOT NULL,
  current_level integer NOT NULL DEFAULT 1 CHECK (current_level BETWEEN 1 AND 99),
  total_score bigint NOT NULL DEFAULT 0 CHECK (total_score >= 0),
  collectables integer NOT NULL DEFAULT 0 CHECK (collectables >= 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  last_played timestamptz NOT NULL DEFAULT now(),
  revision bigint NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS game_slot_user_idx ON game_slot (user_id, last_played DESC);

-- Per-slot documents: `world`, `world:<cityId>`, `progression`.
CREATE TABLE IF NOT EXISTS game_slot_doc (
  slot_id bigint NOT NULL REFERENCES game_slot (id) ON DELETE CASCADE,
  doc_key text NOT NULL,
  schema_version integer NOT NULL DEFAULT 1,
  value jsonb NOT NULL,
  PRIMARY KEY (slot_id, doc_key)
);

-- Retry-safe receipts: the same token can be committed only once per slot.
CREATE TABLE IF NOT EXISTS game_slot_receipt (
  slot_id bigint NOT NULL REFERENCES game_slot (id) ON DELETE CASCADE,
  token uuid NOT NULL,
  kind text NOT NULL,
  value jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (slot_id, token)
);

-- Account-wide documents: settings, key bindings, prompt style, operative progression.
CREATE TABLE IF NOT EXISTS game_account_doc (
  user_id bigint NOT NULL REFERENCES accounts_user (id) ON DELETE CASCADE,
  doc_key text NOT NULL,
  value jsonb NOT NULL,
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, doc_key)
);
