"""Original fortress layers and Surya poses, rendered with planar Blender inside Docker.

Preview establishes the inward-facing guns and sheltered road before the family.
No collision shapes or gameplay actors are generated by this production tool.
"""
import json
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
from render_city_voice import library
from render_wildfire import city

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT/'assets/cutscenes/shattered_aegis_intro'
PREVIEW = ROOT/'.validation/inward-wall'


def scenery(name):
    """Build independent gun decks, a protected gate road or armored command interior at 1920x1080."""
    city.BATCHES.clear()
    city.ORDER = 0
    if name == 'command':
        city.poly('structure', [(90,800),(90,180),(310,80),(1610,80),(1830,180),(1830,800)],(.045,.065,.10))
        for x in [150,440,1420,1710]:
            city.rect('structure',x,200,60,610,(.13,.16,.20))
            city.rect('lights',x+20,230,8,430,(.65,.21,.15))
        city.poly('structure',[(420,790),(520,650),(1400,650),(1500,790)],(.16,.20,.24))
        for x in [430,1290]:
            city.poly('structure',[(x,690),(x+25,580),(x+170,580),(x+190,690)],(.08,.14,.19))
            city.rect('lights',x+40,595,110,40,(.12,.55,.63))
        city.line('lights',[(620,260),(960,190),(1300,260)],(.68,.24,.15),5)
    else:
        city.rect('structure',0,290,1920,510,(.06,.095,.14))
        for x in range(80,1920,310):
            city.poly('structure',[(x,740),(x+15,175),(x+60,130),(x+145,130),(x+175,175),(x+180,740)],(.11,.16,.21))
            city.rect('structure',x-30,215,240,34,(.20,.25,.29))
            # All barrels aim left and back across the residential lights, inward from the border.
            city.poly('structure',[(x+65,178),(x-75,110),(x-87,134),(x+55,203)],(.27,.31,.34))
            city.rect('lights',x+45,295,72,6,(.93,.33,.16))
            for y in range(380,730,80):
                city.line('structure',[(x+40,y),(x+140,y)],(.17,.22,.27),3)
        city.poly('structure',[(0,800),(1450,800),(1810,700),(1920,720),(1920,1080),(0,1080)],(.09,.14,.18))
        city.line('lights',[(0,802),(1450,802),(1810,702)],(.25,.59,.62),4)
        for x in range(60,1360,230):
            city.poly('structure',[(x,798),(x+15,706),(x+140,706),(x+155,798)],(.17,.22,.26))
        # A separate warm road guides the eye to Surya without opening any mission gate.
        city.rect('structure',1430,520,200,280,(.025,.045,.06))
        city.line('lights',[(1450,790),(1450,540),(1610,540),(1610,790)],(.95,.55,.16),5)
        if name == 'shield_road':
            for x in [1080,1280]:
                city.rect('structure',x,760,100,28,(.18,.17,.18))
                for i in range(6): city.rect('lights',x+8+i*14,765,6,16,(1,.36,.12))
            city.arc('lights',1530,750,180,3.3,6.2,(1,.72,.22),7)
    city.render(name,OUT,PREVIEW)
    (OUT/f'{name}_base.png').unlink(missing_ok=True)


def main():
    """Render the review approach first; complete three scene families and a two-cell Surya atlas after inspection."""
    OUT.mkdir(parents=True,exist_ok=True)
    PREVIEW.mkdir(parents=True,exist_ok=True)
    scenery('approach')
    if '--preview' in sys.argv: return
    scenery('shield_road')
    scenery('command')
    lib=library()
    lib['clear']()
    for col,action in enumerate(['idle','gesture']):
        lib['character']('surya_prime',action,2,offset=(col*512+256,64),scale=1.8)
    lib['render'](OUT/'surya.png',1024,512)
    (OUT/'manifest.json').write_text(json.dumps(dict(
        generator='Original planar Blender geometry in axiom-force-cutscene Docker image',
        scenery=[1920,1080],atlas=[1024,512],cell=[512,512],rows=['surya_prime'],columns=['calm','shield'],
        reused=['neon_rust_aftermath/poses.png','deployment/live/city_base.png','deployment/live/city_structure.png','deployment/live/city_lights.png','characters/rendered/heavy_atlas.png'],
        palette='Established red/gold Kaito, hydro Oceanus, violet Titan, prism Aura, emerald Mirage, solar gold Surya; original armored heavy Voss silhouette',
        rights='Original project geometry, no third-party stock or sampled atmosphere',
        source='tools/cutscene/render_inward_wall.py; render_city_voice.library',
        audio='Twelve ElevenLabs multilingual_v2 cues and original seeded atmosphere; exact text, IDs/settings and hashes in cues/speech_provenance.json'
    ),indent=2)+'\n')


if __name__=='__main__':
    main()
